const assert=require('node:assert/strict');
const {distance,actual}=require('./diagnose_mb.cjs');
const g={nodes:{},edges:{}};
for(let i=0;i<=5;i++)g.nodes[i]={home:i===5,food:false,seen:1};
for(let i=0;i<5;i++)g.edges[i]={from:String(i),to:String(i+1),action:'walk',seen:1,samples:1,energy_sum:0,matches:0,misses:0};
assert.equal(actual(g,'0','home',2),null);
assert.equal(distance(g,'0','home',2),null);
assert.equal(distance(g,'0','home',2,{depth:Infinity}),5);
assert.equal(actual(g,'1','home',2),4);
assert.equal(distance(g,'1','home',17280000002),null);
assert.equal(distance(g,'1','home',17280000002,{fresh:false}),4);
assert.equal(distance(g,'1','home',2,{allowed:[]}),null);
assert.equal(distance(g,'1','home',2,{allowed:['1']}),4);
g.edges[1].action='run';
assert.equal(distance(g,'1','home',2),null);
assert.equal(distance(g,'1','home',2,{run:true}),4);
g.nodes[5].home=false;g.nodes[0].home=true;
assert.equal(distance(g,'5','home',2,{depth:Infinity,run:true}),null);
assert.equal(distance(g,'5','home',2,{depth:Infinity,run:true,undirected:true}),5);
